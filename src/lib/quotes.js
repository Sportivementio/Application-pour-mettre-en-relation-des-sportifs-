// Choisir une citation aléatoire
export function randomQuote() {
  return QUOTES[Math.floor(Math.random() * QUOTES.length)]
}

// Filtrer par sport
export function quotesBySport(sportId) {
  if (!sportId || sportId === 'all') return QUOTES
  return QUOTES.filter(q => q.sport === sportId)
}
